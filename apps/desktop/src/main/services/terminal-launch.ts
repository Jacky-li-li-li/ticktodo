/**
 * terminal-launch — 在用户终端里打开命令（macOS）。
 *
 * 为什么必须走终端：pi 用 `process.stdin/stdout.isTTY` 判定交互模式，非 TTY 会静默降级成
 * print（headless）模式；从 GUI 进程里 `spawn(pi, {stdio:'ignore'})` 拿不到 TUI。
 * 所以这里生成一个可执行 `.command` 脚本，用 `open` 交给终端（LaunchServices）执行。
 *
 * 纪律：
 *  - 只用 argv 数组 + POSIX 单引号转义，不拼 shell 字符串（路径/标题可含空格、引号、中文）。
 *  - 脚本落 `cache/launch/`（可再生层），0700；避免把正文写进 data/（同步层）。
 *  - `open` 不走 AppleScript，因此不需要「自动化」权限；失败再显式 fallback `open -a Terminal`。
 */

import { execFile } from 'node:child_process'
import fs from 'node:fs'
import path from 'node:path'
import { promisify } from 'node:util'
import type { TerminalOpenSpec } from '@tick/ai-pi'

const execFileAsync = promisify(execFile)

const KEEP_MS = 24 * 60 * 60 * 1000

export type OpenFile = (file: string) => Promise<void>

/** POSIX 单引号转义：单引号内除 `'` 外无特殊字符，换行也可安全保留 */
export function shellQuote(value: string): string {
  return `'${value.replace(/'/g, `'\\''`)}'`
}

/** 生成终端脚本内容（导出以便测试：不需要真的打开终端就能断言转义/argv/env） */
export function renderTerminalScript(spec: TerminalOpenSpec): string {
  const lines = ['#!/bin/sh', '# generated by Tick — safe to delete (cache layer)']
  for (const [key, value] of Object.entries(spec.env ?? {})) {
    lines.push(`export ${key}=${shellQuote(value)}`)
  }
  lines.push(
    `cd ${shellQuote(spec.cwd)} || exit 1`,
    `exec ${[spec.executable, ...spec.args].map(shellQuote).join(' ')}`,
    '',
  )
  return lines.join('\n')
}

function cleanupOld(launchDir: string): void {
  let names: string[]
  try {
    names = fs.readdirSync(launchDir)
  } catch {
    return
  }
  for (const name of names) {
    if (!name.endsWith('.command')) continue
    const file = path.join(launchDir, name)
    try {
      if (Date.now() - fs.statSync(file).mtimeMs > KEEP_MS) fs.rmSync(file, { force: true })
    } catch {
      /* 忽略 */
    }
  }
}

/**
 * 创建「在终端里打开」的实现。
 *
 * @param launchDir 脚本目录（cache/launch，调用方保证 0700）
 * @param openImpl  测试注入；默认用系统 `open`
 */
export function createTerminalLauncher(
  launchDir: string,
  openImpl?: OpenFile,
): (spec: TerminalOpenSpec) => Promise<void> {
  const open: OpenFile =
    openImpl ??
    (async (file: string) => {
      if (process.platform !== 'darwin') {
        throw new Error('当前只支持 macOS 终端拉起（open）')
      }
      try {
        await execFileAsync('/usr/bin/open', [file])
      } catch {
        // 默认 .command 处理程序被改过时，显式指定 Terminal
        await execFileAsync('/usr/bin/open', ['-a', 'Terminal', file])
      }
    })

  return async (spec: TerminalOpenSpec): Promise<void> => {
    if (!spec.executable) throw new Error('终端拉起缺少可执行文件')
    if (!fs.existsSync(spec.cwd)) throw new Error(`cwd 不存在：${spec.cwd}`)
    fs.mkdirSync(launchDir, { recursive: true, mode: 0o700 })
    cleanupOld(launchDir)

    // Terminal 的环境来自用户 shell 而不是 Tick 进程：Tick 用自定义数据根时必须显式带过去，
    // 否则终端里的 pi extension 会写回默认根（两侧 split-brain）。
    const env: Record<string, string> = { ...spec.env }
    const tickHome = process.env.TICK_HOME?.trim()
    if (tickHome) env.TICK_HOME = tickHome

    const file = path.join(
      launchDir,
      `${new Date().toISOString().replace(/[:.]/g, '-')}-${Math.random().toString(36).slice(2, 8)}.command`,
    )
    fs.writeFileSync(file, renderTerminalScript({ ...spec, env }), { mode: 0o700 })
    try {
      await open(file)
    } catch (err) {
      // 脚本没被终端接走：删掉，避免留下无主文件
      try {
        fs.rmSync(file, { force: true })
      } catch {
        /* 忽略 */
      }
      throw new Error(`打开终端失败：${(err as Error).message}`)
    }
  }
}

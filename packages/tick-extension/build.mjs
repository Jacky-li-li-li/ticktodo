/**
 * 把 pi CLI 版扩展打成单文件：dist/index.js
 *
 * 为什么必须 bundle：pi 用 jiti 直接执行 ~/.pi/agent/extensions/tick/index.js，
 * 那个位置没有 node_modules，`typebox` / `./todos-file.ts` 都解析不到。
 */
import { build } from 'esbuild'

await build({
  entryPoints: ['src/index.ts'],
  outfile: 'dist/index.js',
  bundle: true,
  platform: 'node',
  format: 'esm',
  target: 'node22',
  // pi 在运行时提供的模块保持外置（类型导入本来就会被擦除）
  external: ['@earendil-works/pi-coding-agent'],
  banner: {
    js: '// Tick extension bundle — generated by packages/tick-extension/build.mjs. Do not edit.',
  },
})

console.log('built packages/tick-extension/dist/index.js')

/**
 * 把 MCP server 打成单文件：dist/tick-mcp.mjs
 *
 * 为什么 bundle：客户端（pi / WorkBuddy / shim）只拿到一个入口文件，
 * 那台机器/那个位置不一定有 node_modules；与 tick-extension 的构建策略一致。
 */
import { build } from 'esbuild'

await build({
  entryPoints: ['src/index.ts'],
  outfile: 'dist/tick-mcp.mjs',
  bundle: true,
  platform: 'node',
  format: 'esm',
  target: 'node22',
  banner: { js: '#!/usr/bin/env node\n// Tick MCP server bundle — generated by packages/mcp-server/build.mjs.' },
  // node: 内置模块由 esbuild 自动外置；这里只需确保 SDK 打进产物
  logLevel: 'info',
})
